"""Reference definition of the model's input features (log-mel spectrogram).

This file is the single source of truth for the features. The firmware
implementation in //modules/features must reproduce it, and the training code
must compute features through `log_mel()` here (or something tested against
it), so that a model trained on the host sees the same numbers on the chip.

Definition, per frame:
  - 400 samples (25 ms at 16 kHz), advanced by 160 samples (10 ms)
  - int16 samples scaled to [-1, 1), times a periodic Hann window
  - zero-padded to a 512-point FFT; power spectrum |X|^2 of bins 0..256
  - 40 triangular mel filters (HTK mel scale, unnormalised), 80 Hz to 7600 Hz
  - natural log of (band energy + 1e-6)

Running this script regenerates the golden test vectors used by the firmware
unit test and by the on-chip self-test:
  uv run tools/host/log_mel_reference.py
"""

import pathlib
import sys

import numpy as np

SAMPLE_RATE = 16000
FRAME_LENGTH = 400
HOP = 160
FFT_SIZE = 512
NUM_MELS = 40
MEL_LOW_HZ = 80.0
MEL_HIGH_HZ = 7600.0
LOG_FLOOR = 1e-6

_GOLDEN_FRAMES = 18
_GOLDEN_HEADER = pathlib.Path(__file__).resolve().parents[2] / "modules" / "features" / "log_mel_golden.h"


def _hz_to_mel(hz):
    return 2595.0 * np.log10(1.0 + np.asarray(hz, dtype=np.float64) / 700.0)


def _mel_to_hz(mel):
    return 700.0 * (10.0 ** (np.asarray(mel, dtype=np.float64) / 2595.0) - 1.0)


def mel_filterbank() -> np.ndarray:
    """[NUM_MELS, FFT_SIZE // 2 + 1] triangular filter weights."""
    edges_hz = _mel_to_hz(np.linspace(_hz_to_mel(MEL_LOW_HZ), _hz_to_mel(MEL_HIGH_HZ), NUM_MELS + 2))
    bin_hz = np.arange(FFT_SIZE // 2 + 1) * SAMPLE_RATE / FFT_SIZE
    bank = np.zeros((NUM_MELS, len(bin_hz)))
    for m in range(NUM_MELS):
        low, centre, high = edges_hz[m], edges_hz[m + 1], edges_hz[m + 2]
        rising = (bin_hz - low) / (centre - low)
        falling = (high - bin_hz) / (high - centre)
        bank[m] = np.maximum(0.0, np.minimum(rising, falling))
    return bank


def log_mel(pcm: np.ndarray) -> np.ndarray:
    """int16 PCM at 16 kHz -> [num_frames, NUM_MELS] log-mel features."""
    samples = np.asarray(pcm, dtype=np.float64) / 32768.0
    num_frames = (len(samples) - FRAME_LENGTH) // HOP + 1
    if num_frames <= 0:
        return np.zeros((0, NUM_MELS))
    window = 0.5 - 0.5 * np.cos(2.0 * np.pi * np.arange(FRAME_LENGTH) / FRAME_LENGTH)
    frames = np.stack([samples[i * HOP : i * HOP + FRAME_LENGTH] for i in range(num_frames)]) * window
    power = np.abs(np.fft.rfft(frames, n=FFT_SIZE, axis=1)) ** 2
    return np.log(power @ mel_filterbank().T + LOG_FLOOR)


def golden_pcm(num_samples: int) -> np.ndarray:
    """Deterministic test signal built from integer arithmetic only.

    Two triangle-wave tones (about 440 Hz and 3 kHz) plus pseudo-random
    noise, so every mel band has energy and the tones land in known bands.
    The firmware test regenerates exactly these samples with the same
    arithmetic, so no audio file has to be shipped.
    """
    out = np.zeros(num_samples, dtype=np.int16)
    lcg = 12345
    phase_a = phase_b = 0
    for n in range(num_samples):
        lcg = (lcg * 1664525 + 1013904223) & 0xFFFFFFFF
        noise = ((lcg >> 16) & 0xFFFF) - 32768  # [-32768, 32767]
        phase_a = (phase_a + 1802) & 0xFFFF  # ~440 Hz
        phase_b = (phase_b + 12288) & 0xFFFF  # 3 kHz
        tri_a = abs(phase_a - 32768) - 16384  # [-16384, 16384]
        tri_b = abs(phase_b - 32768) - 16384
        out[n] = noise // 8 + tri_a // 2 + tri_b // 4
    return out


def write_golden() -> None:
    num_samples = FRAME_LENGTH + HOP * (_GOLDEN_FRAMES - 1)
    expected = log_mel(golden_pcm(num_samples))
    assert expected.shape == (_GOLDEN_FRAMES, NUM_MELS)
    lines = [
        "// Generated by tools/host/log_mel_reference.py. Do not edit.",
        "//",
        "// Expected log-mel features for the deterministic test signal that",
        "// GoldenPcmGenerator (log_mel_golden_signal.h) produces. Used by the host",
        "// unit test and by the on-chip self-test.",
        "",
        "#pragma once",
        "",
        "#include <cstddef>",
        "",
        "namespace device_ml::features::golden {",
        "",
        f"inline constexpr size_t kNumSamples = {num_samples};",
        f"inline constexpr size_t kNumFrames = {_GOLDEN_FRAMES};",
        f"inline constexpr size_t kNumMels = {NUM_MELS};",
        "",
        "inline constexpr float kExpected[kNumFrames][kNumMels] = {",
    ]
    for frame in expected:
        values = ", ".join(f"{v:.6f}f" for v in frame)
        lines.append(f"    {{{values}}},")
    lines += ["};", "", "}  // namespace device_ml::features::golden", ""]
    _GOLDEN_HEADER.write_text("\n".join(lines))
    print(f"Wrote {_GOLDEN_HEADER} ({_GOLDEN_FRAMES} frames x {NUM_MELS} mels)")
    print(f"feature range: {expected.min():.2f} .. {expected.max():.2f}")


if __name__ == "__main__":
    write_golden()
    sys.exit(0)
